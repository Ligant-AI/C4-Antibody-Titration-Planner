export function integerPower(base: number, exponent: number): number {
    if (!Number.isInteger(exponent) || exponent < 0) {
        throw new Error(`integerPower expects a non-negative integer exponent, received ${exponent}`);
    }
    let result = 1;
    let square = base;
    let remaining = exponent;
    while (remaining > 0) {
        if (remaining % 2 === 1)
            result *= square;
        remaining = Math.floor(remaining / 2);
        if (remaining > 0)
            square *= square;
    }
    return result;
}
export function seriesValue(top: number, factor: number, index: number): number {
    if (!Number.isInteger(index) || index < 1) {
        throw new Error(`seriesValue expects a one-based integer index, received ${index}`);
    }
    return top / integerPower(factor, index - 1);
}
export function series(top: number, factor: number, points: number): number[] {
    return Array.from({ length: points }, (_, i) => seriesValue(top, factor, i + 1));
}
